USE INSTRAGRAM;
DROP TABLE IF EXISTS posts;
DROP TABLE IF EXISTS users;
CREATE TABLE users(
  ID INT,
  AGE INT,
  NAME VARCHAR(30) NOT NULL,
  email VARCHAR(50) UNIQUE,
  FOLLOWING INT,
  PRIMARY KEY(ID)
  );
  
  
  CREATE TABLE posts(
  ID INT PRIMARY KEY,
  CONTENT VARCHAR(100),
  USER_ID INT,
  FOREIGN KEY(USER_ID) REFERENCES users(ID)
  );